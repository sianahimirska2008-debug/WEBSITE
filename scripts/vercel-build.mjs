/**
 * Build command for Vercel (and any Postgres host).
 *
 * Local dev and tests use SQLite (prisma/schema.prisma). Serverless hosts can't
 * keep a SQLite file, so here we:
 *   1. derive prisma/postgres/schema.prisma (same models, provider = postgresql)
 *   2. generate the Prisma client for it
 *   3. apply the schema to the database (`prisma db push`; refuses destructive changes)
 *   4. if SEED_DEMO_DATA=true and the database is empty, load the demo data
 *   5. next build
 */
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const run = (cmd) => execSync(cmd, { stdio: "inherit", env: process.env });
const url = process.env.DATABASE_URL ?? "";

if (!/^postgres(ql)?:\/\//.test(url)) {
  console.error(
    "\nDATABASE_URL must point to a Postgres database for deployment (got " +
      (url ? url.split(":")[0] + ":…" : "nothing") +
      ").\nIn Vercel: Storage → Create Database → Neon (or Prisma Postgres), connect it to this project, then redeploy.\n",
  );
  process.exit(1);
}

const schema = readFileSync("prisma/schema.prisma", "utf8").replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
if (!schema.includes('provider = "postgresql"')) throw new Error("Could not switch the Prisma provider to postgresql");
mkdirSync("prisma/postgres", { recursive: true });
writeFileSync("prisma/postgres/schema.prisma", "// Generated by scripts/vercel-build.mjs. Do not edit.\n" + schema);

const S = "--schema prisma/postgres/schema.prisma";
run(`npx prisma generate ${S}`);
run(`npx prisma db push ${S} --skip-generate`);

if (process.env.SEED_DEMO_DATA === "true") {
  const { PrismaClient } = await import("@prisma/client");
  const db = new PrismaClient();
  const users = await db.user.count();
  await db.$disconnect();
  if (users === 0) {
    console.log("Empty database: loading demo data");
    run("npx tsx prisma/seed.ts");
  } else {
    console.log(`Database already has ${users} users: skipping demo data`);
  }
}

run("npx next build");
